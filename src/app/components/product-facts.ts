export function sourceCard(
  id: string,
  kind: "art" | "cake" | "bento" = "art",
): SourceCard {
  const highlights = {
    art: "17960390717969447",
    cake: "18098844766853643",
    bento: "18036632201228509",
  };
  return {
    image: `/images/cards/${id}.webp`,
    original: `/images/cards/${id}.jpg`,
    source: `https://www.instagram.com/stories/highlights/${highlights[kind]}/`,
  };
}
